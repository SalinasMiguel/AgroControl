-- V13__responsable_fotos_humedad_y_compras.sql — Lo que pidieron las pestañas: quién se hace cargo de una incidencia,
-- sus fotos, la humedad de recibo de cada cultivo, el documento de cada compra y los repuestos equivalentes.

ALTER TABLE agrocontrol.incidencia
    ADD COLUMN id_responsable bigint REFERENCES agrocontrol.usuario (id_usuario);

CREATE TABLE agrocontrol.incidencia_foto (
    id_foto        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia  bigint NOT NULL REFERENCES agrocontrol.incidencia (id_incidencia),
    tipo_contenido varchar(20) NOT NULL,
    tamano         integer NOT NULL,
    datos          bytea NOT NULL,
    id_usuario     bigint NOT NULL REFERENCES agrocontrol.usuario (id_usuario),
    fecha          timestamp NOT NULL DEFAULT now()
);
CREATE INDEX idx_incidencia_foto_incidencia ON agrocontrol.incidencia_foto (id_incidencia);

-- Humedad a la que se paga el grano; sin dato no se ajusta el rendimiento.
ALTER TABLE agrocontrol.cultivo
    ADD COLUMN humedad_estandar_pct numeric(5,2),
    ADD CONSTRAINT cultivo_humedad_estandar_check CHECK (humedad_estandar_pct >= 0 AND humedad_estandar_pct < 100);
UPDATE agrocontrol.cultivo SET humedad_estandar_pct = 13 WHERE lower(nombre) IN ('soya', 'trigo');
UPDATE agrocontrol.cultivo SET humedad_estandar_pct = 14 WHERE lower(nombre) IN ('maíz', 'maiz', 'sorgo');

ALTER TABLE agrocontrol.movimiento_insumo
    ADD COLUMN proveedor varchar(120),
    ADD COLUMN numero_factura varchar(40);

-- Cada par se guarda una vez, con el id menor primero: la equivalencia vale en los dos sentidos.
CREATE TABLE agrocontrol.insumo_equivalencia (
    id_insumo      bigint NOT NULL REFERENCES agrocontrol.insumo (id_insumo),
    id_equivalente bigint NOT NULL REFERENCES agrocontrol.insumo (id_insumo),
    PRIMARY KEY (id_insumo, id_equivalente),
    CONSTRAINT insumo_equivalencia_orden_check CHECK (id_insumo < id_equivalente)
);
CREATE INDEX idx_insumo_equivalencia_equivalente ON agrocontrol.insumo_equivalencia (id_equivalente);
